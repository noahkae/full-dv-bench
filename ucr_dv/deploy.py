"""
Export a profile for the car / the ROS 2 (Galactic) stack.

    ros/ucr_dv_ros/config/<profile>.json   the profile itself (the node loads it)
    ros/ucr_dv_ros/config/<profile>.yaml   flattened ROS parameters, e.g.
                                           planner.max_gap, sensor.lidar.min_cluster_points
                                           - tunable live with `ros2 param set`

The ROS node (ros/ucr_dv_ros/ucr_dv_ros/stack_node.py) builds the same
ucr_dv.pipeline.Stack, so what passed the benches is exactly what runs.
"""
from __future__ import annotations

import json
import os

from . import paths
from .core import registry

ROS_PKG = os.path.join(paths.ROOT, 'ros', 'ucr_dv_ros')


def flat_params(profile):
    """{'planner.max_gap': 6.0, 'sensor.lidar.min_cluster_points': 3, ...} incl. defaults."""
    out = {}
    for kind, st in profile.stages.items():
        e = registry.get(kind, st['name'])
        for k, v in e.resolve(st.get('params')).items():
            out['{}.{}'.format(kind, k)] = v
    for s in profile.rig.perception():
        if not s.algorithm:
            continue
        kind = 'lidar' if s.type == 'lidar' else 'camera'
        try:
            e = registry.get(kind, s.algorithm['name'])
        except KeyError:
            continue
        for k, v in e.resolve(s.algorithm.get('params')).items():
            out['sensor.{}.{}'.format(s.name, k)] = v
    return out


def _yaml_value(v):
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return repr(v)
    return '"{}"'.format(str(v).replace('"', '\\"'))


def export_ros(profile, out_dir=None):
    out_dir = out_dir or os.path.join(ROS_PKG, 'config')
    os.makedirs(out_dir, exist_ok=True)
    jpath = os.path.join(out_dir, profile.name + '.json')
    with open(jpath, 'w') as f:
        json.dump(profile.to_dict(), f, indent=2)
    lines = ['# generated by ucr-dv-stack from profile "{}"'.format(profile.name),
             'ucr_dv_stack:', '  ros__parameters:',
             '    profile: "{}"'.format(os.path.basename(jpath)),
             '    pipeline_hz: {}'.format(profile.pipeline_hz)]
    for k, v in sorted(flat_params(profile).items()):
        lines.append('    {}: {}'.format(k, _yaml_value(v)))
    ypath = os.path.join(out_dir, profile.name + '.yaml')
    with open(ypath, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    return jpath, ypath


def fsds_settings(profile):
    """An FSDS/AirSim settings.json 'Vehicles' block for the rig (real FSDS or the team's sim)."""
    sensors, cameras = {}, {}
    for s in profile.rig.sensors:
        m = s.mount
        if s.type == 'lidar':
            hfov = float(s.p('hfov'))
            ch = int(s.p('channels'))
            sensors[s.name] = {'SensorType': 6, 'Enabled': s.enabled, 'X': m.x, 'Y': -m.y, 'Z': -m.z,
                               'Roll': m.roll, 'Pitch': m.pitch, 'Yaw': -m.yaw, 'NumberOfLasers': ch,
                               'PointsPerScan': int(ch * round(hfov / float(s.p('h_res_deg')))),
                               'VerticalFOVUpper': s.p('vfov_upper'), 'VerticalFOVLower': s.p('vfov_lower'),
                               'HorizontalFOVStart': -hfov / 2, 'HorizontalFOVEnd': hfov / 2,
                               'RotationsPerSecond': s.p('rate_hz'), 'DrawDebugPoints': False}
        elif s.type in ('camera', 'stereo'):
            cameras[s.name] = {'CaptureSettings': [{'ImageType': 0, 'Width': int(s.p('width')),
                                                    'Height': int(s.p('height')), 'FOV_Degrees': s.p('hfov')}],
                               'X': m.x, 'Y': -m.y, 'Z': -m.z, 'Pitch': -m.pitch, 'Roll': m.roll, 'Yaw': -m.yaw}
        elif s.type == 'imu':
            sensors['Imu'] = {'SensorType': 2, 'Enabled': True}
        elif s.type == 'gnss':
            sensors['Gps'] = {'SensorType': 3, 'Enabled': True}
        elif s.type == 'gss':
            sensors['GSS'] = {'SensorType': 7, 'Enabled': True}
    return {'SettingsVersion': 1.2, 'Vehicles': {'FSCar': {'Sensors': sensors, 'Cameras': cameras}},
            '_note': 'NED frame: y and z are negated relative to ucr_dv\'s ENU mounts.'}
